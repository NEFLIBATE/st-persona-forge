export function getWorldGroup(theme) {
    return WORLD_GROUPS.find(group => group.themes.includes(theme))?.id || '';
}
export function getChoiceOptions(kind, {theme = 'modern', category = 'all', query = ''} = {}) {
    const groups = CHOICE_GROUPS[kind] || [];
    const world = getWorldGroup(theme);
    const tokens = String(query).trim().toLocaleLowerCase().split(/\s+/).filter(Boolean);
    return groups.flatMap(group => {
        if (category === 'recommended' && kind === 'identity' && world && !group.worlds.includes(world)) return [];
        if (!['all', 'recommended'].includes(category) && category !== group.id) return [];
        return group.items.filter(value => tokens.every(token => `${group.label} ${value}`.toLocaleLowerCase().includes(token)))
            .map(value => ({value, group: group.label, groupId: group.id}));
    });
}
export function toggleTrait(current, value, max = 500) {
    const values = [...new Set(String(current || '').split(/[、，,；;\n]+/).map(part => part.trim()).filter(Boolean))];
    const index = values.indexOf(value);
    if (index < 0) values.push(value); else values.splice(index, 1);
    const result = values.join('、');
    if (result.length > max) throw new Error(`性格关键词最多${max}字符，请先减少部分内容。`);
    return result;
}
